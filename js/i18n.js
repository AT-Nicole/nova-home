/* ---------- runtime ---------- */
let CURRENT_LANG = "en";

function detectLang() {
  const params = new URLSearchParams(window.location.search);
  const forced = params.get("lang");
  if (forced && I18N[forced]) return forced;
  const saved = localStorage.getItem("hw_lang");
  if (saved && I18N[saved]) return saved;
  return "en";
}

function t(key) {
  const dict = I18N[CURRENT_LANG] || I18N.en;
  if (dict[key] !== undefined) return dict[key];
  if (I18N.en[key] !== undefined) return I18N.en[key];
  return key;
}

function localizeField(obj, base, lang) {
  /* pick {base}_{lang} field with fallback to {base}_en then {base} */
  if (!obj) return "";
  const l = lang || CURRENT_LANG;
  if (obj[base + "_" + l] !== undefined && String(obj[base + "_" + l]).trim() !== "") return obj[base + "_" + l];
  if (obj[base + "_en"] !== undefined && String(obj[base + "_en"]).trim() !== "") return obj[base + "_en"];
  return obj[base] !== undefined ? obj[base] : "";
}

function applyStaticI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach(function (el) {
    const v = t(el.getAttribute("data-i18n"));
    if (v !== null && v !== undefined) el.textContent = v;
  });
  root.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  root.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  root.querySelectorAll("[data-i18n-title]").forEach(function (el) {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
}

function setLang(lang, persist) {
  if (!I18N[lang]) lang = "en";
  CURRENT_LANG = lang;
  if (persist !== false) localStorage.setItem("hw_lang", lang);
  const meta = LANG_META[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = meta.dir;
  applyStaticI18n(document);
  document.querySelectorAll(".lang-current").forEach(function (el) { el.textContent = lang.toUpperCase(); });
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: lang } }));
  /* keep URL ?lang= in sync for hreflang/sharing (only when param exists) */
  const params = new URLSearchParams(window.location.search);
  if (params.has("lang")) {
    params.set("lang", lang);
    history.replaceState(null, "", window.location.pathname + "?" + params.toString() + window.location.hash);
  }
}

document.addEventListener("DOMContentLoaded", function () {
  setLang(detectLang(), false);
});
